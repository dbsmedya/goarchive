// showCreate returns SHOW CREATE TABLE's text for table on db.
func showCreate(t *testing.T, db *sql.DB, table string) string {
	t.Helper()
	var name, ddl string
	if err := db.QueryRowContext(context.Background(), "SHOW CREATE TABLE `"+table+"`").Scan(&name, &ddl); err != nil {
		t.Fatal(err)
	}
	return ddl
}

// createGIPK creates t (data VARCHAR(50)) with a generated invisible primary key: the
// session variable and the CREATE must run on the same session, so both use one *sql.Conn.
func createGIPK(t *testing.T, db *sql.DB) {
	t.Helper()
	ctx := context.Background()
	conn, err := db.Conn(ctx)
	if err != nil {
		t.Fatal(err)
	}
	defer func() { _ = conn.Close() }()
	for _, q := range []string{"SET SESSION sql_generate_invisible_primary_key = ON", "CREATE TABLE t (data VARCHAR(50) NOT NULL) ENGINE=InnoDB"} {
		if _, err := conn.ExecContext(ctx, q); err != nil {
			t.Fatalf("%s: %v", q, err)
		}
	}
}

// TestMySQLExplicitColumns (M7-3, G25): the copy read, the INSERT and the sha256 hash name
// every column the source reports (sourceColumns), so columns that SELECT * cannot see are
// copied and verified. Each case archives two rows under sha256; side A has the condition,
// proved on the server's own SHOW CREATE TABLE, and side B is the same table with that one
// fact undone. Both sides archive, and the destination holds the asserted values.
// Pair, per case:
//   - invisible: payload INVISIBLE seeded 'secret-1', 'secret-2' → copied; payload visible → copied;
//   - GIPK: my_row_id generated by sql_generate_invisible_primary_key, ids 5 and 9 → kept;
//     my_row_id declared visibly → kept;
//   - generated: an invisible STORED generated source column into a plain destination column
//     → 42, 84; the generated column visible → 42, 84;
//   - destination invisible: note INVISIBLE on the destination only → copied; visible → copied;
//   - case only: the destination spells ID and Email → copied and verified; same spelling → the same.
func TestMySQLExplicitColumns(t *testing.T) {
	for _, tc := range []struct {
		name     string
		src, dst [2]string // side A's and side B's CREATE TABLE t; "gipk" is createGIPK
		seed     string
		key      string // primary_key
		witness  string // the text side A's SHOW CREATE TABLE holds and side B's does not
		onDst    bool   // the witness is on the destination
		q        string // read on the destination after the run
		want     []string
	}{
		{
			name: "invisible",
			src: [2]string{"CREATE TABLE t (id BIGINT NOT NULL PRIMARY KEY, payload VARCHAR(32) DEFAULT 'd' INVISIBLE) ENGINE=InnoDB",
				"CREATE TABLE t (id BIGINT NOT NULL PRIMARY KEY, payload VARCHAR(32) DEFAULT 'd') ENGINE=InnoDB"},
			seed: "INSERT INTO t (id, payload) VALUES (1, 'secret-1'), (2, 'secret-2')", key: "id", witness: "INVISIBLE",
			q: "SELECT CONCAT(id, '/', payload) FROM t ORDER BY id", want: []string{"1/secret-1", "2/secret-2"},
		},
		{
			name: "GIPK",
			src:  [2]string{"gipk", "CREATE TABLE t (my_row_id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY, data VARCHAR(50) NOT NULL) ENGINE=InnoDB"},
			seed: "INSERT INTO t (my_row_id, data) VALUES (5, 'alpha'), (9, 'beta')", key: "my_row_id", witness: "INVISIBLE",
			q: "SELECT CONCAT(my_row_id, '/', data) FROM t ORDER BY my_row_id", want: []string{"5/alpha", "9/beta"},
		},
		{
			name: "generated",
			src: [2]string{"CREATE TABLE t (id BIGINT NOT NULL PRIMARY KEY, amount INT NOT NULL, doubled INT GENERATED ALWAYS AS (amount * 2) STORED INVISIBLE) ENGINE=InnoDB",
				"CREATE TABLE t (id BIGINT NOT NULL PRIMARY KEY, amount INT NOT NULL, doubled INT GENERATED ALWAYS AS (amount * 2) STORED) ENGINE=InnoDB"},
			dst:  [2]string{"CREATE TABLE t (id BIGINT NOT NULL PRIMARY KEY, amount INT NOT NULL, doubled INT) ENGINE=InnoDB"},
			seed: "INSERT INTO t (id, amount) VALUES (1, 21), (2, 42)", key: "id", witness: "INVISIBLE",
			q: "SELECT CONCAT(id, '/', doubled) FROM t ORDER BY id", want: []string{"1/42", "2/84"},
		},
		{
			name: "destination invisible",
			src:  [2]string{"CREATE TABLE t (id BIGINT NOT NULL PRIMARY KEY, note VARCHAR(50)) ENGINE=InnoDB"},
			dst: [2]string{"CREATE TABLE t (id BIGINT NOT NULL PRIMARY KEY, note VARCHAR(50) INVISIBLE) ENGINE=InnoDB",
				"CREATE TABLE t (id BIGINT NOT NULL PRIMARY KEY, note VARCHAR(50)) ENGINE=InnoDB"},
			seed: "INSERT INTO t VALUES (1, 'kept-1'), (2, 'kept-2')", key: "id", witness: "INVISIBLE", onDst: true,
			q: "SELECT CONCAT(id, '/', note) FROM t ORDER BY id", want: []string{"1/kept-1", "2/kept-2"},
		},
		{
			name: "case only",
			src:  [2]string{"CREATE TABLE t (id BIGINT NOT NULL PRIMARY KEY, email VARCHAR(64) NOT NULL, UNIQUE KEY uq_email (email)) ENGINE=InnoDB"},
			dst: [2]string{"CREATE TABLE t (ID BIGINT NOT NULL PRIMARY KEY, Email VARCHAR(64) NOT NULL, UNIQUE KEY uq_email (Email)) ENGINE=InnoDB",
				"CREATE TABLE t (id BIGINT NOT NULL PRIMARY KEY, email VARCHAR(64) NOT NULL, UNIQUE KEY uq_email (email)) ENGINE=InnoDB"},
			seed: "INSERT INTO t VALUES (1, 'a@example.com'), (2, 'b@example.com')", key: "id", witness: "`Email`", onDst: true,
			q: "SELECT CONCAT(id, '/', email) FROM t ORDER BY id", want: []string{"1/a@example.com", "2/b@example.com"},
		},
	} {
		for side, label := range []string{"A", "B"} {
			t.Run(tc.name+"/"+label, func(t *testing.T) {
				e := newEnv(t, "cols")
				pick := func(ddl [2]string) string {
					if ddl[side] == "" {
						return ddl[0]
					}
					return ddl[side]
				}
				srcDDL, dstDDL := pick(tc.src), pick(tc.dst)
				if dstDDL == "" {
					dstDDL = srcDDL
				}
				for _, p := range []struct {
					db  *sql.DB
					ddl string
				}{{e.src, srcDDL}, {e.dst, dstDDL}} {
					if p.ddl == "gipk" {
						createGIPK(t, p.db)
					} else {
						execAll(t, p.db, p.ddl)
					}
				}
				execAll(t, e.src, tc.seed)
				witnessDB := e.src
				if tc.onDst {
					witnessDB = e.dst
				}
				if got := strings.Contains(showCreate(t, witnessDB, "t"), tc.witness); got != (side == 0) {
					t.Fatalf("SHOW CREATE TABLE t holds %q = %v, want %v on side %s", tc.witness, got, side == 0, label)
				}
				cfg := e.config(t, job(t, jobspec.Archive, "\n    root_table: t\n    primary_key: "+tc.key+"\n    where: \"1=1\"\n"))
				rep := e.mustRun(t, cfg)
				if rep.Roots != 2 {
					t.Errorf("report = %+v, want 2 roots", rep)
				}
				if got := texts(t, e.dst, tc.q); !equal(got, tc.want) {
					t.Errorf("destination %s = %v, want %v", tc.q, got, tc.want)
				}
				if got := count(t, e.src, "SELECT COUNT(*) FROM t"); got != 0 {
					t.Errorf("source t = %d rows, want 0 archived", got)
				}
			})
		}
	}
}
